// Generates styles/v2/tokens.css from replica/design/tokens.json.
// tokens.json is the single source of truth for colour; this file is never
// edited by hand. `node scripts/build-tokens.mjs --check` exits 1 when the
// committed CSS is stale (used by the test suite).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "replica/design/tokens.json"), "utf8"));
const out = resolve(root, "styles/v2/tokens.css");

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const channels = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
};
const block = (theme) =>
  Object.entries(tokens.color[theme])
    .map(([k, v]) => `  --c-${kebab(k)}: ${channels(v)}; /* ${v} */`)
    .join("\n");

const css = `/* GENERATED by scripts/build-tokens.mjs from replica/design/tokens.json. Do not edit. */
/* Colours are RGB channels so Tailwind opacity modifiers work: rgb(var(--c-ink) / 0.5). */

:root {
  color-scheme: light;
${block("light")}
  --shadow-card: ${tokens.shadow.card};
  --shadow-pop: ${tokens.shadow.pop};
  --ease: ${tokens.motion.ease};
  --dur-micro: ${tokens.motion.micro};
  --dur-panel: ${tokens.motion.panel};
}

/* Dark: pinned by data-theme, or the OS setting when nothing is pinned. Both blocks are identical. */
:root[data-theme="dark"] {
  color-scheme: dark;
${block("dark")}
  --shadow-card: 0 0 0 1px rgb(255 255 255 / 0.04);
  --shadow-pop: 0 12px 32px -8px rgb(0 0 0 / 0.6), 0 0 0 1px rgb(255 255 255 / 0.06);
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block("dark").replace(/^ {2}/gm, "    ")}
    --shadow-card: 0 0 0 1px rgb(255 255 255 / 0.04);
    --shadow-pop: 0 12px 32px -8px rgb(0 0 0 / 0.6), 0 0 0 1px rgb(255 255 255 / 0.06);
  }
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== css) {
    console.error("styles/v2/tokens.css is stale. Run: node scripts/build-tokens.mjs");
    process.exit(1);
  }
  console.log("tokens.css is in sync");
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, css);
  console.log("wrote", out);
}
